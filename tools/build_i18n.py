"""Generate the dependency-free browser dictionary from the shared EN/RU JSON catalogs.

Run: python tools/build_i18n.py
CI:  python tools/build_i18n.py --check
"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LOCALES = ROOT / "sl_guard" / "locales"
OUTPUT = ROOT / "sl_guard" / "static" / "sl_guard_i18n.js"


def render() -> str:
    catalogs = {
        locale: json.loads((LOCALES / f"{locale}.json").read_text(encoding="utf-8"))
        for locale in ("en", "ru")
    }
    if set(catalogs["en"]) != set(catalogs["ru"]):
        raise ValueError("EN and RU translation key sets must match")

    # Keep browser and Python strings sourced from the same JSON files.
    dictionary = json.dumps(catalogs, ensure_ascii=False, indent=2)
    return (
        "// Generated by tools/build_i18n.py from sl_guard/locales/*.json. DO NOT EDIT.\n"
        "const CATALOGS = Object.freeze(" + dictionary + ");\n"
        "let activeLocale = 'en';\n"
        "\n"
        "/** Set UI language from InvenTree context.locale. Unsupported languages fall back to English. */\n"
        "export function selectLocale(locale) {\n"
        "  activeLocale = String(locale || 'en').toLowerCase().split(/[-_]/)[0] === 'ru' ? 'ru' : 'en';\n"
        "  return activeLocale;\n"
        "}\n"
        "\n"
        "/** Translate a stable key, replacing only named {parameters}. */\n"
        "export function tr(key, parameters = {}) {\n"
        "  const message = CATALOGS[activeLocale]?.[key] ?? CATALOGS.en[key] ?? key;\n"
        "  return message.replace(/\\{([a-z_]+)\\}/gi, (match, name) =>\n"
        "    Object.prototype.hasOwnProperty.call(parameters, name) ? String(parameters[name]) : match);\n"
        "}\n"
    )


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="Verify generated JS is up to date")
    args = parser.parse_args()
    content = render()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != content:
            raise SystemExit("Localization JS is outdated; run python tools/build_i18n.py")
        print("Localization JavaScript matches shared JSON catalogs")
    else:
        OUTPUT.write_text(content, encoding="utf-8")
        print(f"Generated {OUTPUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
